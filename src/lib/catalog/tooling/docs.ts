import type { Catalog } from "../catalog";
import { CATEGORIES, CATEGORY_LABELS, type Workflow } from "../schema";

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const METHOD: Record<string, string> = { schema: "schema", rule: "rule", model: "model review" };

/** One sentence on what the gather step retrieves, from its settings. */
function researchSummary(w: Workflow): string {
  const g = w.steps.find((s) => s.mode === "gather")?.gather;
  if (!g) return "";
  const parts: string[] = [];
  if (g.search) parts.push(`up to ${g.search.maxSearches} web searches`);
  if (g.fetch?.urlInputs?.length) parts.push(`reads the pages you link`);
  if (g.fetch?.fromSearch) parts.push(`reads the top ${g.fetch.fromSearch} results in full`);
  return parts.length ? `Each run: ${parts.join(", ")}, at most ${g.fetch?.maxPages ?? 0} pages.` : "";
}

/** One workflow's reference entry. Descriptions may carry "Who it's for:" and "Limitations:" sentences, shown as their own lines. */
function workflowDetails(w: Workflow): string[] {
  const [what, rest = ""] = w.description.split(" Who it's for: ");
  const [who, limits] = rest.split(" Limitations: ");
  const root = w.outputSchema?.type === "object" ? w.outputSchema.properties : {};
  const outputs = Object.entries(root).map(([key, node]) => node.title ?? key);
  const lines = [`### ${w.name} \`${w.id}@${w.version}\``, "", what];
  if (who) lines.push("", `**Who it's for:** ${who}`);
  lines.push(
    "",
    `**Inputs:** ${w.inputs.map((i) => `${i.label}${i.required ? "" : " (optional)"}`).join(", ")}`,
    "",
    `**Output:** ${outputs.join(", ")}`,
    ...(w.tools.length
      ? [
          "",
          `**Tools:** ${w.tools.map((t) => `\`${t.id}\``).join(", ")} (read-only). ${researchSummary(w)}`,
          "",
          "**Evidence:** every source the run retrieved is stored with the result and listed with its URL, title, date and whether the page was read in full or only seen as a search result. Pages that could not be read are listed too. Cited claims are checked against the retrieved text before the output is accepted.",
        ]
      : []),
    "",
    "**Checks:**",
    "",
    ...w.evaluation.criteria.map((c) => `- ${c.critical ? "**critical** " : ""}${METHOD[c.method]}: ${c.description}`),
  );
  if (limits) lines.push("", `**Limitations:** ${limits}`);
  return lines;
}

/** docs/catalog.md: a browsable index of every definition, generated so it never drifts from the JSON. */
export function renderCatalogDocs(catalog: Catalog): string {
  const lines: string[] = [
    "# Workflow catalog",
    "",
    "<!-- Generated by `npm run catalog:docs` from catalog/. Do not edit by hand. -->",
    "",
    `${catalog.workflows.length} workflows · ${catalog.workflows.filter((w) => w.status === "available").length} executable · ${new Set(catalog.workflows.map((w) => w.category)).size} categories`,
    "",
  ];
  for (const category of CATEGORIES) {
    const list = catalog.workflows.filter((w) => w.category === category);
    if (!list.length) continue;
    lines.push(`## ${CATEGORY_LABELS[category]}`, "", "| Workflow | Status | Summary | Needs first | Tools |", "| --- | --- | --- | --- | --- |");
    for (const w of list) {
      const file = catalog.sources[w.id] ? `../catalog/workflows/${catalog.sources[w.id]}` : "";
      const needs = w.dependencies.filter((d) => d.required).map((d) => `\`${d.workflowId}\``).join(", ") || "—";
      const tools = w.tools.map((t) => `\`${t.id}\``).join(", ") || "—";
      lines.push(`| [${cell(w.name)}](${file}) \`${w.id}@${w.version}\` | ${w.status === "available" ? "executable" : "definition"} | ${cell(w.summary)} | ${needs} | ${tools} |`);
    }
    lines.push("");
  }
  const generic = catalog.workflows.filter((w) => w.schemaVersion === 2 && w.outputSchema);
  if (generic.length) {
    lines.push(
      "## Workflow details",
      "",
      "Every schema-v2 workflow, which runs on the generic executor. Checks marked **critical** reject an output on their own; the others count toward the quality score.",
      "",
    );
    for (const category of CATEGORIES) {
      for (const w of generic.filter((g) => g.category === category)) lines.push(...workflowDetails(w), "");
    }
  }
  const shared = catalog.registry?.sharedInputs ?? [];
  if (shared.length) {
    lines.push("## Shared inputs", "", "Defined once in `catalog/shared-inputs.json` and referenced with `{ \"use\": \"<key>\" }`.", "", "| Key | Label | Type | Used by |", "| --- | --- | --- | --- |");
    for (const s of shared) {
      const users = catalog.workflows.filter((w) => w.inputs.some((i) => i.key === s.key && i.shared)).map((w) => `\`${w.id}\``);
      lines.push(`| \`${s.key}\` | ${cell(s.label)} | ${s.type} | ${users.join(", ") || "—"} |`);
    }
    lines.push("");
  }
  const tools = catalog.registry?.tools ?? [];
  if (tools.length) {
    lines.push("## Tools", "", "| Id | Name | Provided today | Setup |", "| --- | --- | --- | --- |");
    for (const t of tools) lines.push(`| \`${t.id}\` | ${cell(t.name)} | ${t.available ? "yes" : "no"} | ${cell(t.setup ?? "")} |`);
    lines.push("");
  }
  return lines.join("\n");
}
